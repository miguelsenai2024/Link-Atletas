import { expect, test } from '@playwright/test'
import { AxeBuilder } from '@axe-core/playwright'

// Public landing interactions do not require an API or database.
test.beforeEach(async ({ page }) => {
  await page.route('**/api/auth/session', route => route.fulfill({ json: { user: null } }))
  await page.goto('/')
})

test('menu móvel fecha pelo teclado e pelos links', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const menu = page.getByRole('button', { name: /menu/ })
  await menu.click()
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await expect(menu).toBeFocused()
  await menu.click()
  await page.locator('#navigation').getByRole('link', { name: 'Perguntas' }).click()
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await expect(page).toHaveURL(/#perguntas$/)
})

test('prévia valida respostas, aplica modalidade e abre cadastro de atleta', async ({ page }) => {
  const result = page.locator('#match-result')
  const submit = page.getByRole('button', { name: 'Descobrir meu próximo passo' })
  await submit.click()
  await expect(result).toBeHidden()
  await page.locator('[data-sport="Corrida"]').first().click()
  await expect(page.getByLabel('O que te coloca em movimento?')).toHaveValue('Corrida')
  await page.getByLabel('Qual é o seu momento?').selectOption('constância')
  await page.getByLabel('Como você prefere treinar?').selectOption('Online')
  await submit.click()
  await expect(result).toContainText('Corrida · Acompanhamento online.')
  await page.getByLabel('Qual é o seu momento?').selectOption('performance')
  await expect(result).toBeHidden()
  await submit.click()
  await expect(result).toContainText('Ajustar seus treinos')
  await result.getByRole('link').click()
  await expect(page).toHaveURL(/\/login\?cadastro=1&perfil=atleta$/)
  await expect(page.getByLabel('Nome completo')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sou atleta', exact: true })).toHaveClass('active')
})

test('treinadores seguem para o cadastro correto e login segue disponível', async ({ page }) => {
  await page.getByRole('link', { name: 'Sou treinador', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?cadastro=1&perfil=treinador$/)
  await expect(page.getByLabel('Nome completo')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sou treinador', exact: true })).toHaveClass('active')
  await page.getByRole('link', { name: 'Voltar para o início' }).click()
  await page.locator('#navigation').getByRole('link', { name: 'Entrar', exact: false }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByLabel('Nome completo')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Entrar na plataforma', exact: true })).toBeVisible()
})

test('FAQ abre uma resposta por vez e funciona pelo teclado', async ({ page }) => {
  const faq = page.locator('.motion-accordion')
  const questions = faq.getByRole('button')
  await expect(questions).toHaveCount(6)
  await expect(faq.locator('[aria-expanded="true"]')).toHaveCount(0)
  await expect(faq.getByRole('region')).toHaveCount(0)
  await faq.screenshot({ path: test.info().outputPath('faq-closed.png') })
  await questions.first().click()
  await expect(faq.getByRole('region', { name: 'Preciso ser atleta profissional?' })).toContainText('Não. A LinkAtletas atende')
  await questions.nth(1).click()
  await expect(questions.first()).toHaveAttribute('aria-expanded', 'false')
  await expect(faq.getByRole('region')).toHaveCount(1)
  await expect(faq.getByRole('region', { name: 'Como encontro o treinador certo?' })).toContainText('modalidade, nível, objetivo')
  await questions.nth(3).focus()
  await page.keyboard.press('Space')
  await expect(questions.nth(3)).toHaveAttribute('aria-expanded', 'true')
  await expect(questions.nth(1)).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Enter')
  await expect(faq.getByRole('region')).toHaveCount(0)
  expect((await new AxeBuilder({ page }).include('.motion-accordion').analyze()).violations).toEqual([])
})

test('FAQ anima a resposta e recalcula a altura ao mudar para celular', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const faq = page.locator('.motion-accordion')
  const question = faq.getByRole('button', { name: 'Quem pode ver meus vídeos e dados?' })
  await question.click()
  const panel = page.locator(`[id="${await question.getAttribute('aria-controls')}"]`)
  await expect(panel).toBeVisible()
  await expect.poll(() => panel.evaluate(el => Math.abs(el.getBoundingClientRect().height - el.firstElementChild!.scrollHeight))).toBeLessThan(2)
  await faq.screenshot({ path: test.info().outputPath('faq-open-desktop.png') })
  const desktopHeight = await panel.evaluate(el => el.getBoundingClientRect().height)
  await page.setViewportSize({ width: 320, height: 800 })
  await expect.poll(() => panel.evaluate(el => Math.abs(el.getBoundingClientRect().height - el.firstElementChild!.scrollHeight))).toBeLessThan(2)
  expect(await panel.evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThan(desktopHeight)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await faq.screenshot({ path: test.info().outputPath('faq-open-mobile.png') })
  expect((await new AxeBuilder({ page }).include('.motion-accordion').analyze()).violations).toEqual([])
  await question.click()
  await expect(panel).toHaveAttribute('aria-hidden', 'true')
  await expect.poll(() => panel.evaluate(el => el.getBoundingClientRect().height)).toBeLessThan(1)
})
